/** item_id（如 "minecraft:white_wool" 或 "white_wool[facing=north]"）→ 中文名 */
export function zhItemName(itemId: string): string {
  if (!itemId) return '未知'
  const clean = itemId.split('[')[0]
  const withNs = clean.startsWith('minecraft:') ? clean : `minecraft:${clean}`
  if (ZH[withNs]) return ZH[withNs]
  // 回退：去前缀、下划线转空格、首字母大写
  const pure = clean.replace('minecraft:', '')
  return pure.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase())
}
